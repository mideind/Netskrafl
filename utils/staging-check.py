sys.path.append(_ROOT)

# The projects whose backend this check may be run against
ALLOWED_PROJECTS = frozenset(("explo-dev",))

# The registered test users: (user id, nickname, full name)
TEST_USERS: List[Tuple[str, str, str]] = [
    ("test:staging-check-a", "StagingCheckA", "Staging Check A"),
    ("test:staging-check-b", "StagingCheckB", "Staging Check B"),
]
# The device id of the guest test user
GUEST_DEVICE_ID = "staging-check-guest-0001"
# The locale of the test users and their games
LOCALE = "en_US"
# A robot that is available without a subscription (level: common words)
ROBOT = "robot-15"

# The login token format; must match what src/skrafluser.py issues and accepts
# (CURRENT_KID for Explo, JWT_ALGORITHM, JWT_AUDIENCE)
TOKEN_KID = "2025-02-21:1"
TOKEN_ALGORITHM = "HS256"
TOKEN_AUDIENCE = "explo-client"

# A valid word in each supported locale's vocabulary
VALID_WORDS: Mapping[str, str] = {
    "en_US": "house",
    "en_GB": "colour",
    "is_IS": "hestur",
    "pl_PL": "kot",
    "nb_NO": "hest",
    "nn_NO": "hest",
    "ga_IE": "teach",
}
# A string that is not a word in any of them
INVALID_WORD = "xqzzkj"

# Result codes of the API (Error in src/config.py)
LEGAL = 0
GAME_OVER = 99

BOARD_SIZE = 15
ROWS = "ABCDEFGHIJKLMNO"
# A request slower than this fails the check
SLOW_SECONDS = 5.0
TIMEOUT = 30

Json = Dict[str, Any]


class Report:
    """Collects the results of the checks and prints them as they come"""

    def __init__(self) -> None:
        self.failed = 0
        self.passed = 0

    def check(self, ok: bool, what: str) -> bool:
        if ok:
            self.passed += 1
        else:
            self.failed += 1
        print(("  ok    " if ok else "  FAIL  ") + what, flush=True)
        return ok

    def section(self, title: str) -> None:
        print(f"\n{title}", flush=True)


class Backend:
    """The backend under test, and a record of all requests made to it"""

    def __init__(self, base: str) -> None:
        self.base = base.rstrip("/")
        # (path, status, seconds) of every request
        self.requests: List[Tuple[str, int, float]] = []

    def session(self) -> requests.Session:
        s = requests.Session()
        s.headers["User-Agent"] = "staging-check/1.0"
        return s

    def call(
        self,
        s: requests.Session,
        path: str,
        body: Optional[Json] = None,
        *,
        method: str = "POST",
        headers: Optional[Mapping[str, str]] = None,
    ) -> Tuple[int, Json]:
        """Make a request; return its status and its JSON answer
        (an empty dictionary if the answer is not a JSON object)"""
        t0 = time.monotonic()
        r = s.request(
            method,
            self.base + path,
            json=({} if body is None else body) if method == "POST" else None,
            headers=dict(headers or {}),
            timeout=TIMEOUT,
        )
        self.requests.append((path, r.status_code, time.monotonic() - t0))
        try:
            j = r.json()
        except ValueError:
            j = None
        return r.status_code, j if isinstance(j, dict) else {}


class Player:
    """A logged-in test user"""

    def __init__(self, backend: Backend, name: str) -> None:
        self.backend = backend
        self.name = name
        self.s = backend.session()
        self.id = ""

    def post(self, path: str, body: Optional[Json] = None) -> Tuple[int, Json]:
        return self.backend.call(self.s, path, body)

    def game(self, game_id: str) -> Json:
        """The state of a game, as this player sees it"""
        status, j = self.post("/gamestate", {"game": game_id})
        if status != 200 or not j.get("ok"):
            raise RuntimeError(f"/gamestate for {self.name}: {status} {j.get('ok')}")
        return j["game"]


def board_of(game: Json) -> List[str]:
    """The board of a game as the moves service wants it: one string per
    row, '.' for an empty square, a lower case letter for a tile and an
    upper case letter for a blank tile standing for that letter. Built
    from the game's list of moves: [player, [coordinate, tiles, score]],
    where the coordinate is row + column ("H8") for a horizontal move
    and column + row ("8H") for a vertical one, and a blank tile is
    written '?' followed by its letter."""
    rows = [["."] * BOARD_SIZE for _ in range(BOARD_SIZE)]
    for _, (co, tiles, _) in game.get("newmoves", []):
        place(rows, co, tiles)
    return ["".join(r) for r in rows]


def squares(co: str, tiles: str) -> List[Tuple[int, int, str]]:
    """The squares that a move covers: (row, column, tile), where the
    tile is a letter, or '?' and a letter for a blank tile. An empty
    list for a move that is not a tile move (pass, exchange, resign)."""
    if not co or not tiles or not (co[0] in ROWS or co[0].isdigit()):
        return []
    horizontal = co[0] in ROWS
    try:
        if horizontal:
            row, col = ROWS.index(co[0]), int(co[1:]) - 1
        else:
            row, col = ROWS.index(co[-1]), int(co[:-1]) - 1
    except ValueError:
        return []
    result: List[Tuple[int, int, str]] = []
    i = 0
    while i < len(tiles):
        tile = tiles[i]
        if tile == "?":
            i += 1
            tile = "?" + tiles[i]
        if not (0 <= row < BOARD_SIZE and 0 <= col < BOARD_SIZE):
            return []
        result.append((row, col, tile))
        if horizontal:
            col += 1
        else:
            row += 1
        i += 1
    return result


def place(rows: List[List[str]], co: str, tiles: str) -> None:
    """Put the tiles of a move on the board, leaving alone the squares that
    are already covered (a move's tiles include those it passes through)"""
    for row, col, tile in squares(co, tiles):
        if rows[row][col] == ".":
            rows[row][col] = tile[1].upper() if tile[0] == "?" else tile


def make_move(player: Player, game_id: str) -> Tuple[bool, str, Json]:
    """Have the moves service generate a move for the player whose turn
    it is, and submit it. Returns (accepted, description, the answer)."""
    game = player.game(game_id)
    board = board_of(game)
    rack = "".join(t[0] for t in game.get("rack", []))
    status, j = player.post(
        "/moves",
        {
            "board": board,
            "rack": rack,
            "locale": game.get("locale", LOCALE),
            "board_type": game.get("board_type", "explo"),
            "limit": 1,
        },
    )
    if status != 200:
        return False, f"/moves answered {status}", {}
    found: List[Json] = j.get("moves", [])
    if found:
        co, word = found[0]["co"], found[0]["w"]
        rows = [list(r) for r in board]
        moves = [
            f"{ROWS[row]}{col + 1}={tile}"
            for row, col, tile in squares(co, word)
            if rows[row][col] == "."
        ]
        what = f"'{word}' at {co}"
    else:
        # No move is possible with this rack: pass
        moves, what = ["pass"], "a pass (no move possible)"
    status, j = player.post(
        "/submitmove",
        {"uuid": game_id, "mcount": game.get("num_moves", 0), "moves": moves},
    )
    ok = status == 200 and j.get("result") == LEGAL
    return ok, f"{what}: {status}, result {j.get('result')}", j


def resign(player: Player, game_id: str) -> Tuple[int, Json]:
    game = player.game(game_id)
    return player.post(
        "/submitmove",
        {"uuid": game_id, "mcount": game.get("num_moves", 0), "moves": ["rsgn"]},
    )


def games_of(player: Player) -> List[Json]:
    status, j = player.post("/gamelist")
    if status != 200:
        raise RuntimeError(f"/gamelist for {player.name}: {status}")
    return j.get("gamelist", [])


def challenges_of(player: Player) -> List[Json]:
    status, j = player.post("/challengelist")
    if status != 200:
        raise RuntimeError(f"/challengelist for {player.name}: {status}")
    return j.get("challengelist", [])


def clear_away(players: List[Player]) -> int:
    """Finish the games and remove the challenges that an earlier,
    interrupted run may have left behind. Returns their number."""
    n = 0
    for _ in range(2):
        # Two rounds: a game is resigned by the player whose turn it is
        for p in players:
            for g in games_of(p):
                if g.get("zombie"):
                    # A finished game that has not been seen: see it
                    p.post("/gamestate", {"game": g["uuid"], "delete_zombie": True})
                    n += 1
                elif g.get("my_turn"):
                    resign(p, g["uuid"])
                    n += 1
    for p in players:
        for c in challenges_of(p):
            action = "decline" if c.get("received") else "retract"
            p.post(
                "/challenge",
                {"destuser": c["userid"], "action": action, "key": c.get("key")},
            )
            n += 1
    return n


def check_health(backend: Backend, report: Report) -> None:
    report.section("Health")
    s = backend.session()
    for path in ("/health/live", "/health/ready"):
        status, _ = backend.call(s, path, method="GET")
        report.check(status == 200, f"{path}: {status}")
    status, _ = backend.call(s, "/gamelist")
    report.check(status == 401, f"an API call without a login is refused: {status}")


def check_guest(backend: Backend, report: Report, auth_secret: str) -> None:
    report.section("Guest user")
    guest = Player(backend, "the guest")
    status, j = backend.call(
        guest.s,
        "/oauth_anon",
        {"sub": GUEST_DEVICE_ID, "clientType": "ios", "locale": LOCALE},
        headers={"Authorization": f"Bearer {auth_secret}"},
    )
    guest.id = j.get("user_id", "")
    if not report.check(
        status == 200 and j.get("status") == "success" and bool(guest.id),
        f"guest login: {status}",
    ):
        return
    clear_away([guest])
    status, j = guest.post("/loaduserprefs")
    report.check(status == 200 and j.get("ok") is True, f"preferences: {status}")
    status, j = guest.post("/userstats")
    report.check(
        status == 200 and j.get("result") == LEGAL, f"own statistics: {status}"
    )
    status, j = guest.post("/firebase_token")
    report.check(
        status == 200 and j.get("ok") is True and bool(j.get("token")),
        f"token for the real-time database: {status}",
    )

    report.section("Game against a robot")
    status, j = guest.post("/initgame", {"opp": ROBOT})
    game_id: str = j.get("uuid", "")
    if not report.check(
        status == 200 and j.get("ok") is True and bool(game_id),
        f"game created: {status} {j.get('err', '')}",
    ):
        return
    before = guest.game(game_id).get("num_moves", 0)
    ok, what, _ = make_move(guest, game_id)
    report.check(ok, f"move generated and accepted, {what}")
    game = guest.game(game_id)
    after = game.get("num_moves", 0)
    report.check(
        after == before + 2,
        f"the robot answered (moves in the game: {before} before, {after} after)",
    )
    report.check(
        any(g.get("uuid") == game_id for g in games_of(guest)),
        "the game is in the game list",
    )
    status, j = resign(guest, game_id)
    report.check(
        status == 200 and j.get("result") == GAME_OVER,
        f"game resigned: {status}, result {j.get('result')}",
    )
    report.check(
        all(g.get("uuid") != game_id for g in games_of(guest)),
        "the game has left the game list",
    )
    status, j = guest.post("/recentlist", {"count": 5})
    recent: List[Json] = j.get("recentlist", [])
    report.check(
        status == 200 and any(g.get("uuid") == game_id for g in recent),
        f"the game is in the list of recent games: {status}",
    )

    report.section("Vocabularies")
    for locale, word in VALID_WORDS.items():
        status, j = guest.post(
            "/wordcheck",
            {"locale": locale, "word": word, "words": [word, INVALID_WORD]},
        )
        valid = {w: v for w, v in j.get("valid", [])}
        report.check(
            status == 200 and valid.get(word) is True and valid.get(INVALID_WORD) is False,
            f"{locale}: '{word}' is a word and '{INVALID_WORD}' is not ({status})",
        )


def mint_token(user_id: str, project_id: str, secret: str) -> str:
    """A short-lived login token for a user, as the backend issues them"""
    now = datetime.now(UTC)
    claims: Dict[str, Any] = {
        "iss": project_id,
        "sub": user_id,
        "exp": now + timedelta(minutes=10),
        "iat": now,
        "jti": str(uuid.uuid4()),
        "aud": TOKEN_AUDIENCE,
    }
    return jwt.encode(
        claims, secret, algorithm=TOKEN_ALGORITHM, headers={"kid": TOKEN_KID}
    )


def check_registered(
    backend: Backend, report: Report, project_id: str, token_secret: str
) -> None:
    report.section("Registered users")
    players: List[Player] = []
    for user_id, nickname, _ in TEST_USERS:
        p = Player(backend, nickname)
        status, j = p.post(
            "/oauth_explo",
            {"token": mint_token(user_id, project_id, token_secret), "clientType": "ios"},
        )
        p.id = j.get("user_id", "")
        hint = "" if status == 200 else " (does the user exist? see --create-users)"
        if not report.check(
            status == 200 and j.get("status") == "success" and p.id == user_id,
            f"{nickname} logs in with a token: {status}{hint}",
        ):
            return
        players.append(p)
    a, b = players
    clear_away(players)

    report.section("Challenge")
    status, j = a.post("/challenge", {"destuser": b.id, "action": "issue"})
    report.check(
        status == 200 and j.get("result") == LEGAL,
        f"{a.name} challenges {b.name}: {status}, result {j.get('result')}",
    )
    received = [
        c for c in challenges_of(b) if c.get("received") and c.get("userid") == a.id
    ]
    issued = [
        c for c in challenges_of(a) if not c.get("received") and c.get("userid") == b.id
    ]
    if not report.check(
        len(received) == 1 and len(issued) == 1,
        f"both see the challenge ({len(issued)} issued, {len(received)} received)",
    ):
        return
    status, j = b.post("/initgame", {"opp": a.id, "key": received[0].get("key")})
    game_id: str = j.get("uuid", "")
    if not report.check(
        status == 200 and j.get("ok") is True and bool(game_id),
        f"{b.name} accepts, and the game is created: {status} {j.get('err', '')}",
    ):
        return
    report.check(
        not challenges_of(a) and not challenges_of(b),
        "the challenge has left both lists",
    )

    report.section("Game between two users")
    report.check(
        all(any(g.get("uuid") == game_id for g in games_of(p)) for p in players),
        "the game is in both game lists",
    )
    by_id = {p.id: p for p in players}
    first = by_id.get(j.get("to_move", ""), a)
    second = b if first is a else a
    ok, what, _ = make_move(first, game_id)
    report.check(ok, f"{first.name} moves, {what}")
    n = second.game(game_id).get("num_moves", 0)
    report.check(n == 1, f"{second.name} sees the move (moves in the game: {n})")
    ok, what, _ = make_move(second, game_id)
    report.check(ok, f"{second.name} moves, {what}")

    channel = f"game:{game_id}"
    text = f"staging check {datetime.now(UTC).isoformat(timespec='seconds')}"
    status, j = a.post("/chatmsg", {"channel": channel, "msg": text})
    report.check(
        status == 200 and j.get("ok") is True, f"{a.name} sends a chat message: {status}"
    )
    status, j = b.post("/chatload", {"channel": channel})
    messages: List[Json] = j.get("messages", [])
    report.check(
        status == 200
        and any(m.get("msg") == text and m.get("from_userid") == a.id for m in messages),
        f"{b.name} reads it: {status}",
    )

    # It is now the first player's turn again
    status, j = resign(first, game_id)
    report.check(
        status == 200 and j.get("result") == GAME_OVER,
        f"{first.name} resigns: {status}, result {j.get('result')}",
    )
    report.check(
        all(g.get("uuid") != game_id for g in games_of(first)),
        f"the game has left {first.name}'s game list",
    )
    # The opponent keeps a finished game in the list until it has been seen
    kept = [g for g in games_of(second) if g.get("uuid") == game_id]
    report.check(
        len(kept) == 1 and kept[0].get("zombie") is True,
        f"{second.name} has it in the game list as a finished game",
    )
    status, j = second.post("/gamestate", {"game": game_id, "delete_zombie": True})
    report.check(
        status == 200
        and j.get("ok") is True
        and all(g.get("uuid") != game_id for g in games_of(second)),
        f"and it leaves the list once {second.name} has seen it: {status}",
    )

    report.section("Lists and statistics")
    status, j = second.post("/gamestats", {"game": game_id})
    report.check(
        status == 200 and j.get("result") == GAME_OVER and "scores" in j,
        f"statistics of the finished game: {status}, result {j.get('result')}",
    )
    status, j = a.post("/userstats", {"user": b.id})
    report.check(
        status == 200 and j.get("result") == LEGAL,
        f"another user's statistics: {status}, result {j.get('result')}",
    )
    status, j = a.post("/rating_locale", {"kind": "human"})
    report.check(
        status == 200 and j.get("result") == LEGAL and isinstance(j.get("rating"), list),
        f"rating list: {status}",
    )
    status, j = a.post("/userlist", {"query": "robots"})
    report.check(
        status == 200 and bool(j.get("userlist")), f"list of robots: {status}"
    )
    status, j = a.post("/allgamelists", {"count": 5})
    report.check(
        status == 200
        and any(g.get("uuid") == game_id for g in j.get("recentlist", [])),
        f"all lists in one call, with the finished game among the recent: {status}",
    )


def check_requests(backend: Backend, report: Report) -> None:
    report.section("All requests")
    errors = [(p, s) for p, s, _ in backend.requests if s >= 500]
    report.check(
        not errors,
        f"none of the {len(backend.requests)} requests got a 5xx answer"
        + "".join(f"\n          {p}: {s}" for p, s in errors),
    )
    slow = [(p, t) for p, _, t in backend.requests if t > SLOW_SECONDS]
    times = sorted(t for _, _, t in backend.requests)
    median = times[len(times) // 2] if times else 0.0
    report.check(
        not slow,
        f"none took longer than {SLOW_SECONDS:.0f} s "
        f"(median {median * 1000:.0f} ms, slowest {times[-1] * 1000:.0f} ms)"
        + "".join(f"\n          {p}: {t:.1f} s" for p, t in slow),
    )


def create_users() -> int:
    """Create the registered test users in the database, if they are missing"""
    url = os.environ.get("DATABASE_URL", "")
    if not url:
        print("Set DATABASE_URL to the staging database")
        return 2
    from src.db.postgresql import PostgreSQLBackend

    db = PostgreSQLBackend(database_url=url)
    try:
        for user_id, nickname, full_name in TEST_USERS:
            if db.users.get_by_id(user_id) is not None:
                print(f"{user_id}: exists")
                continue
            # Note: create() replaces an existing user, hence the check above
            db.users.create(
                user_id,
                account=user_id,
                email="",
                nickname=nickname,
                preferences={"full_name": full_name, "email": "", "newbag": True},
                locale=LOCALE,
            )
            print(f"{user_id}: created")
        db.commit()
    finally:
        db.close()
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Play through the backend's key operations on the staging app"
    )
    parser.add_argument("url", nargs="?", help="address of the backend (https://host)")
    parser.add_argument(
        "--create-users",
        action="store_true",
        help="create the registered test users in the database (DATABASE_URL)",
    )
    args = parser.parse_args()

    project_id = os.environ.get("PROJECT_ID", "")
    if project_id not in ALLOWED_PROJECTS:
        print(
            f"PROJECT_ID is '{project_id}': this check is only for "
            f"{', '.join(sorted(ALLOWED_PROJECTS))}"
        )
        return 2
    if args.create_users:
        return create_users()
    if not args.url or not args.url.startswith("https://"):
        parser.error("give the address of the backend (https://host)")

    # The two secrets come from the project's configuration, as the app reads it
    import config

    backend = Backend(args.url)
    report = Report()
    sections: List[Tuple[str, Callable[[], None]]] = [
        ("health", lambda: check_health(backend, report)),
        ("guest", lambda: check_guest(backend, report, config.AUTH_SECRET)),
        (
            "registered users",
            lambda: check_registered(
                backend, report, config.PROJECT_ID, config.TOKEN_SECRET
            ),
        ),
        ("requests", lambda: check_requests(backend, report)),
    ]
    started = time.monotonic()
    for name, run in sections:
        try:
            run()
        except Exception as e:
            # A section that cannot go on has failed; the others still run
            report.check(False, f"the {name} checks stopped: {type(e).__name__}: {e}")
    print(
        f"\n{'PASSED' if report.failed == 0 else 'FAILED'}: "
        f"{report.passed} checks passed, {report.failed} failed, "
        f"{time.monotonic() - started:.0f} s"
    )
    return 0 if report.failed == 0 else 1


if __name__ == "__main__":
    sys.exit(main())

